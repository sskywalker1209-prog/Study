print("월요일부터 일요일 중 번역하고 싶은 요일을 한글로 적어주세요")
yoil = input()
if yoil == "월요일" :
    print("monday")
elif yoil == "화요일" :
    print("tuesday")
elif yoil == "수요일" :
    print("wednesday")
elif yoil == "목요일" :
    print("thursday")
elif yoil == "금요일" :
    print("friday")
elif yoil == "토요일" :
    print("saturday")
elif yoil == "일요일" :
    print("sunday")
else:
    print("한글입력이 잘못 되었습니다.")